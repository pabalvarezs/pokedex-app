/** Normaliza un nombre a una clave estable. */
function toMoveKey(name: string): string {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** Devuelve los datos de un movimiento a partir de su slug o nombre. */
export function getMoveInfo(name: string): MoveRow | undefined {
  const key = toMoveKey(name);
  return MOVES_ES[key] ?? MOVES_ES[MOVE_NAME_ALIASES[key]];
}
